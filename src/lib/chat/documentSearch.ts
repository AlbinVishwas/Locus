import { getIndexDb, IndexUnavailableError } from "@/lib/search/indexDb";
import { hasDocumentsForConversation, search, type SearchResult } from "@/lib/search/query";

/**
 * Runs the deterministic document search for one chat turn, if there's
 * anything to search. This never touches the model: it's the same
 * search() the /search page and /api/search use, called in-process and
 * scoped to this conversation's uploads.
 */

const SEARCH_LIMIT = 50;

export interface DocumentSearchOutcome {
  /** What's shown by default. */
  result: SearchResult;
  /**
   * Set only when `result` is exact mode with zero hits and loose mode
   * finds something -- the "without exact punctuation" fallback the user
   * can switch to with one click, never shown automatically.
   */
  looseAlternative: SearchResult | null;
}

/**
 * The first double-quoted, non-empty phrase in the message, or null. Needs
 * two closing characters at minimum either side of an empty pair, so `""`
 * doesn't count as a (useless) quoted search.
 */
export function extractQuotedText(message: string): string | null {
  const match = message.match(/"([^"]+)"/);
  return match ? match[1] : null;
}

/**
 * Null means "nothing to search" -- either this conversation has no
 * uploaded documents at all (the common case for ordinary chat), in which
 * case the caller changes nothing else about the turn, or the derived
 * query is empty.
 */
export function runDocumentSearch(
  conversationId: string,
  userMessage: string
): DocumentSearchOutcome | null {
  // No index file at all -- e.g. no upload has ever happened on this
  // machine -- means by definition no conversation has documents. Not an
  // error: ordinary chat (no files, no index) is the common case this
  // must stay silent for.
  let db;
  try {
    db = getIndexDb();
  } catch (err) {
    if (err instanceof IndexUnavailableError) return null;
    throw err;
  }
  if (!hasDocumentsForConversation(db, conversationId)) return null;

  const query = (extractQuotedText(userMessage) ?? userMessage).trim();
  if (query === "") return null;

  const result = search(db, query, {
    mode: "exact",
    offset: 0,
    limit: SEARCH_LIMIT,
    scope: conversationId,
  });

  let looseAlternative: SearchResult | null = null;
  if (result.hits.length === 0) {
    const loose = search(db, query, {
      mode: "loose",
      offset: 0,
      limit: SEARCH_LIMIT,
      scope: conversationId,
    });
    if (loose.hits.length > 0) looseAlternative = loose;
  }

  return { result, looseAlternative };
}

